#!/usr/bin/env node
'use strict';

// Bundles samples/*.plank.md and gallery/*.plank.md into player/samples.js,
// so that the player works when opened straight from the disk (file:// pages
// cannot fetch files). Gallery models are listed after the samples, under
// "gallery/<name>". Translations (<name>.<lang>.plank.md with a
// `translation-of` key, see docs/proposals/translations.md) have no planks of
// their own: they go in PLANKMD_TRANSLATIONS[<name>][<lang>], not in the list.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const ORDER = ['square-tower', 'twisted-tower', 'corbel-bridge', 'diving-board', 'leaning-tower'];

const list = (dir) => (fs.existsSync(path.join(root, dir))
  ? fs.readdirSync(path.join(root, dir)).filter((f) => f.endsWith('.plank.md')).map((f) => f.replace(/\.plank\.md$/, ''))
  : []);

const TRANSLATION = /^(.+)\.([a-z]{2,3}(?:-[a-z0-9]+)*)$/i;

function buildSamples() {
  const samples = {};
  const translations = {};
  const add = (dir, prefix, names) => {
    for (const name of names) {
      const text = fs.readFileSync(path.join(root, dir, `${name}.plank.md`), 'utf8');
      const m = name.match(TRANSLATION);
      if (/^translation-of:/m.test(text) && m) (translations[prefix + m[1]] = translations[prefix + m[1]] || {})[m[2]] = text;
      else if (!/^translation-of:/m.test(text)) samples[prefix + name] = text;
    }
  };
  add('samples', '', list('samples')
    .sort((a, b) => ((ORDER.indexOf(a) + 1) || 99) - ((ORDER.indexOf(b) + 1) || 99) || a.localeCompare(b)));
  add('gallery', 'gallery/', list('gallery').sort());
  return '// Generated by scripts/build-samples.js from samples/ and gallery/. Do not edit.\n' +
    `window.PLANKMD_SAMPLES = ${JSON.stringify(samples, null, 2)};\n` +
    `window.PLANKMD_TRANSLATIONS = ${JSON.stringify(translations, null, 2)};\n`;
}

// The player runs the balance check in a Web Worker. A worker cannot load
// local files when the page is opened from the disk, so the sources it needs
// are bundled into player/worker-src.js as a string.
function buildWorkerSource() {
  const src = ['src/plankmd.js', 'src/physics.js'].map((f) => fs.readFileSync(path.join(root, f), 'utf8')).join('\n;\n');
  return `// Generated by scripts/build-samples.js from src/. Do not edit.\nwindow.PLANKMD_WORKER_SRC = ${JSON.stringify(src)};\n`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(root, 'player', 'samples.js'), buildSamples());
  fs.writeFileSync(path.join(root, 'player', 'worker-src.js'), buildWorkerSource());
  console.log('player/samples.js and player/worker-src.js updated');
}

module.exports = { buildSamples, buildWorkerSource };
